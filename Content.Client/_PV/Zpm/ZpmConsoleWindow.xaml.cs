using Content.Shared._PV.Zpm;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PV.Zpm;

[GenerateTypedNameReferences]
public sealed partial class ZpmConsoleWindow : DefaultWindow
{
    public event Action? RefreshPressed;
    public event Action? StartPressed;
    public event Action? EjectCorePressed;
    public event Action<ZpmPowerLevel>? PowerLevelSelected;
    public event Action<bool>? ShutdownPressed;

    public ZpmConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        RefreshButton.OnPressed += _ => RefreshPressed?.Invoke();
        StartButton.OnPressed += _ => StartPressed?.Invoke();
        EjectCoreButton.OnPressed += _ => EjectCorePressed?.Invoke();
        LowButton.OnPressed += _ => PowerLevelSelected?.Invoke(ZpmPowerLevel.Low);
        MediumButton.OnPressed += _ => PowerLevelSelected?.Invoke(ZpmPowerLevel.Medium);
        AverageButton.OnPressed += _ => PowerLevelSelected?.Invoke(ZpmPowerLevel.Average);
        HighButton.OnPressed += _ => PowerLevelSelected?.Invoke(ZpmPowerLevel.High);
        ShutdownButton.OnPressed += _ => ShutdownPressed?.Invoke(false);
        EmergencyShutdownButton.OnPressed += _ => ShutdownPressed?.Invoke(true);
    }

    public void UpdateState(ZpmConsoleBoundInterfaceState state)
    {
        ConnectionLabel.Text = state.Linked ? "ZPM control linked" : "No ZPM control linked";
        CoreLabel.Text = $"Core: {(state.HasCore ? "Inserted" : "Missing")}";
        ConditionLabel.Text = $"Condition: {(state.Online ? state.Condition.ToString() : "Offline")}";
        IntegrityLabel.Text = $"Integrity: {state.Integrity:0.0}%";
        PowerLabel.Text = $"Power: {state.PowerSupplied / 1000f:0} kW supplied / {state.PowerOutput / 1000f:0} kW available  |  Setting: {state.PowerLevel}";
        CoolingLabel.Text = $"Cooling efficiency: {state.CoolingEfficiency:0.0}%";
        ShieldingLabel.Text = $"Shielding integrity: {state.ShieldingEfficiency:0.0}%";
        InletLabel.Text = $"Coolant inlet: {state.CoolantInletTemperature:0.0} K";
        OutletLabel.Text = $"Heat outlet: {state.HeatOutletTemperature:0.0} K";
        VacuumLabel.Text = $"Chamber pressure: {state.ChamberPressure / 1000f:0.00} kPa";

        var enabled = state.Linked;
        LowButton.Disabled = !enabled;
        MediumButton.Disabled = !enabled;
        AverageButton.Disabled = !enabled;
        HighButton.Disabled = !enabled;
        StartButton.Disabled = !enabled || state.Online || !state.HasCore;
        EjectCoreButton.Disabled = !enabled || state.Online || !state.HasCore;
        ShutdownButton.Disabled = !enabled || !state.Online || state.Integrity <= 50f;
        EmergencyShutdownButton.Disabled = !enabled || !state.Online;
    }
}
