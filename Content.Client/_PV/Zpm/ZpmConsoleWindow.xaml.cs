using Content.Shared._PV.Zpm;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._PV.Zpm;

[GenerateTypedNameReferences]
public sealed partial class ZpmConsoleWindow : DefaultWindow
{
    public event Action<int>? OutputPercentChanged;
    public event Action? StartPressed;
    public event Action? EjectCorePressed;
    public event Action<bool>? ShutdownPressed;

    public ZpmConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        OutputBar.IntegerValueChanged += value =>
        {
            OutputPercentLabel.Text = $"{value}%";
            OutputPercentChanged?.Invoke(value);
        };
        StartShutdownButton.OnPressed += _ =>
        {
            if (_online)
                ShutdownPressed?.Invoke(false);
            else
                StartPressed?.Invoke();
        };
        EmergencyShutdownButton.OnPressed += _ => ShutdownPressed?.Invoke(true);
        EjectCoreButton.OnPressed += _ => EjectCorePressed?.Invoke();

        // The spectrum is ordered from the bottom of each meter to the top.
        var spectrum = new[]
        {
            Color.FromHex("#075BFF"),
            Color.FromHex("#00BFFF"),
            Color.FromHex("#00E5D4"),
            Color.FromHex("#00E83B"),
            Color.FromHex("#D8F000"),
            Color.FromHex("#FFB000"),
            Color.FromHex("#FF5A00"),
            Color.FromHex("#F00000"),
        };
        CoreTemperatureBar.Segmented = true;
        CoolantInletBar.Segmented = true;
        HeatOutletBar.Segmented = true;
        CoreTemperatureBar.SegmentColors.AddRange(spectrum);
        CoolantInletBar.SegmentColors.AddRange(spectrum);
        HeatOutletBar.SegmentColors.AddRange(spectrum);
    }

    private bool _online;

    public void UpdateState(ZpmConsoleBoundInterfaceState state)
    {
        _online = state.Online;
        ConnectionLabel.Text = state.Linked ? "ZPM control linked" : "No ZPM control linked";
        CoreLabel.Text = $"Core: {(state.HasCore ? "Inserted" : "Missing")}";
        ConditionLabel.Text = $"Condition: {(state.Online ? state.Condition.ToString() : "Offline")}";
        IntegrityLabel.Text = $"Integrity: {state.Integrity:0.0}%";
        ShieldingLabel.Text = $"Shielding: {state.ShieldingEfficiency:0.0}%";
        VacuumLabel.Text = $"Chamber pressure: {state.ChamberPressure / 1000f:0.00} kPa";
        PowerSuppliedLabel.Text = $"{state.PowerSupplied / 1000f:0} kW supplied";
        PowerAvailableLabel.Text = $"{state.PowerOutput / 1000f:0} kW available";
        OutputPercentLabel.Text = $"{state.OutputPercent}%";
        PowerEfficiencyLabel.Text = $"Power efficiency: {state.PowerEfficiency:0.0}%";

        OutputBar.SetValueWithoutEvent(state.OutputPercent);
        CoreTemperatureBar.SetValueWithoutEvent(state.CoreTemperature);
        CoolantInletBar.SetValueWithoutEvent(state.CoolantInletTemperature);
        HeatOutletBar.SetValueWithoutEvent(state.HeatOutletTemperature);

        CoreTemperatureLabel.Text = FormatTemperature(state.CoreTemperature);
        InletLabel.Text = FormatTemperature(state.CoolantInletTemperature);
        OutletLabel.Text = FormatTemperature(state.HeatOutletTemperature);

        var enabled = state.Linked;
        OutputBar.Disabled = !enabled;
        StartShutdownButton.Text = state.Online ? "Shutdown" : "Start Reactor";
        StartShutdownButton.Disabled = !enabled || (state.Online
            ? state.Integrity <= 50f
            : !state.HasCore);
        EmergencyShutdownButton.Disabled = !enabled || !state.Online;
        EjectCoreButton.Disabled = !enabled || state.Online || !state.HasCore;
    }

    private static string FormatTemperature(float temperatureKelvin)
    {
        if (temperatureKelvin <= 0f)
            return "--";

        var temperatureCelsius = temperatureKelvin - 273.15f;
        return $"{temperatureKelvin:0.0} K\n{temperatureCelsius:0.0} °C";
    }
}
