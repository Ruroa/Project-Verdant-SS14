using Content.Shared._FarHorizons.LimbDamage.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._FarHorizons.LimbDamage.UI;

[GenerateTypedNameReferences]
public sealed partial class LimbTargettingUI : UIWidget
{
    public event Action<LimbTarget>? TargetSelected;

    public LimbTargettingUI()
    {
        RobustXamlLoader.Load(this);

        RandomButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.Random);
        HeadButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.Head);
        TorsoButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.Torso);
        LeftArmButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.LeftArm);
        RightArmButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.RightArm);
        LeftHandButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.LeftHand);
        RightHandButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.RightHand);
        LeftLegButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.LeftLeg);
        RightLegButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.RightLeg);
        LeftFootButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.LeftFoot);
        RightFootButton.OnPressed += _ => TargetSelected?.Invoke(LimbTarget.RightFoot);
    }

    public void SetTarget(LimbTarget target)
    {
        CurrentTargetLabel.Text = Loc.GetString("limb-damage-target-current",
            ("target", Loc.GetString(GetTargetLocaleKey(target))));

        RandomButton.Disabled = target == LimbTarget.Random;
        HeadButton.Disabled = target == LimbTarget.Head;
        TorsoButton.Disabled = target == LimbTarget.Torso;
        LeftArmButton.Disabled = target == LimbTarget.LeftArm;
        RightArmButton.Disabled = target == LimbTarget.RightArm;
        LeftHandButton.Disabled = target == LimbTarget.LeftHand;
        RightHandButton.Disabled = target == LimbTarget.RightHand;
        LeftLegButton.Disabled = target == LimbTarget.LeftLeg;
        RightLegButton.Disabled = target == LimbTarget.RightLeg;
        LeftFootButton.Disabled = target == LimbTarget.LeftFoot;
        RightFootButton.Disabled = target == LimbTarget.RightFoot;
    }

    private static string GetTargetLocaleKey(LimbTarget target) => target switch
    {
        LimbTarget.Random => "limb-damage-target-random",
        LimbTarget.Head => "limb-damage-target-head",
        LimbTarget.Torso => "limb-damage-target-torso",
        LimbTarget.LeftArm => "limb-damage-target-left-arm",
        LimbTarget.RightArm => "limb-damage-target-right-arm",
        LimbTarget.LeftHand => "limb-damage-target-left-hand",
        LimbTarget.RightHand => "limb-damage-target-right-hand",
        LimbTarget.LeftLeg => "limb-damage-target-left-leg",
        LimbTarget.RightLeg => "limb-damage-target-right-leg",
        LimbTarget.LeftFoot => "limb-damage-target-left-foot",
        LimbTarget.RightFoot => "limb-damage-target-right-foot",
        _ => "limb-damage-target-torso",
    };
}
