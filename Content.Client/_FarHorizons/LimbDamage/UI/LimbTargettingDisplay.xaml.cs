using System.Linq;
using System.Numerics;
using Content.Shared._FarHorizons.LimbDamage.Components;
using Robust.Client.GameObjects;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client._FarHorizons.LimbDamage.UI;

/// <summary>
/// Far Horizons-style body diagram: each configured body-part sprite is drawn
/// with an outline shader, and clicking its configured area selects that part.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LimbTargettingDisplay : Control
{
    private static readonly ProtoId<ShaderPrototype> ShaderProto = "LimbTargetting";
    private readonly Dictionary<LimbTarget, ShaderInstance> _shaders = new();
    private LimbTarget? _highlight;
    private LimbTarget? _selection = LimbTarget.Torso;

    private Vector2 CurrentMousePosition =>
        (UserInterfaceManager.MousePositionScaled.Position * UIScale) - GlobalPixelPosition;

    private Vector2 RelativeMousePosition =>
        new(CurrentMousePosition.X / Width / UIScale, CurrentMousePosition.Y / Height / UIScale);

    public event Action<LimbTarget>? OnSelectedLimb;

    public Dictionary<LimbTarget, DrawLimb> DrawLimbs = new();
    public List<DrawLabel> DrawLabels = new();
    public Vector3 DefaultColor = new(1f, 1f, 1f);
    public Vector3 HighlightColor = new(0.55f, 0f, 0f);
    public bool DrawDebugBoxes;
    public bool WithHealth;
    public bool ReadOnly;
    /// <summary>Whether the current mouse hover and selected limb should receive the selection outline.</summary>
    public bool HighlightSelection = true;
    public Dictionary<LimbTarget, float> LimbDamage = new();

    public LimbTargettingDisplay()
    {
        RobustXamlLoader.Load(this);
    }

    public void InitShaders(IPrototypeManager prototypes)
    {
        ClearShaders();
        var baseShader = prototypes.Index(ShaderProto).InstanceUnique();
        baseShader.SetParameter("outerColor", DefaultColor);

        foreach (var limb in DrawLimbs.Keys)
            _shaders[limb] = baseShader.Duplicate();
    }

    public void ClearShaders() => _shaders.Clear();

    public void InitializeDisplay(IPrototypeManager prototypes, SpriteSystem sprites,
        ProtoId<LimbTargettingPrototype> proto, bool withHealth = false)
    {
        var targetter = prototypes.Index(proto);
        WithHealth = withHealth;
        DrawDebugBoxes = targetter.DrawDebugBoxes;
        DrawLimbs = targetter.Limbs.ToDictionary(
            layer => layer.Limb,
            layer => new DrawLimb(sprites, layer.Area, layer.Sprites));
        DrawLabels = targetter.Labels
            .Select(label => new DrawLabel(label.Text, label.Position, label.FontPath, label.FontSize))
            .ToList();
        InitShaders(prototypes);
    }

    public void UpdateSelection(LimbTarget? selection) => _selection = selection;

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        if (_shaders.Count == 0)
            return;

        UpdateShaders();

        foreach (var (limb, draw) in DrawLimbs.Reverse())
        {
            handle.UseShader(_shaders[limb]);
            foreach (var texture in draw.Textures)
                handle.DrawTextureRect(texture, UIBox2.FromDimensions(0, 0, Width * UIScale, Height * UIScale));
            handle.UseShader(null);

            if (DrawDebugBoxes)
            {
                handle.DrawRect(
                    new UIBox2(
                        new Vector2(draw.Area.Left * Width * UIScale, draw.Area.Top * Height * UIScale),
                        new Vector2(draw.Area.Right * Width * UIScale, draw.Area.Bottom * Height * UIScale)),
                    Color.Red,
                    false);
            }
        }

        foreach (var label in DrawLabels)
        {
            var position = new Vector2(label.Position.X * Width * UIScale, label.Position.Y * Height * UIScale);
            handle.DrawString(label.Font, position, label.Text, new Color(DefaultColor.X, DefaultColor.Y, DefaultColor.Z));
        }
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);
        if (ReadOnly || args.Handled || args.Function != EngineKeyFunctions.UIClick)
            return;

        _highlight = GetHighlight();
        if (_highlight is not { } limb)
            return;

        _selection = limb;
        OnSelectedLimb?.Invoke(limb);
        args.Handle();
    }

    private LimbTarget? GetHighlight()
    {
        foreach (var (limb, draw) in DrawLimbs)
        {
            if (Contains(draw.Area, RelativeMousePosition))
                return limb;
        }

        return null;
    }

    private void UpdateShaders()
    {
        _highlight = HighlightSelection ? GetHighlight() : null;
        foreach (var (limb, shader) in _shaders)
        {
            var color = WithHealth ? HealthColor(limb) : DefaultColor;
            var selected = HighlightSelection && (limb == _highlight || limb == _selection);
            shader.SetParameter("outerColor", selected ? HighlightColor : color);
            shader.SetParameter("innerFill", WithHealth || selected);
            shader.SetParameter("innerColor", WithHealth ? color : HighlightColor);
        }
    }

    private Vector3 HealthColor(LimbTarget limb)
    {
        if (!LimbDamage.TryGetValue(limb, out var damage) || damage <= 25f)
            return new Vector3(0f, 1f, 0f);
        if (damage <= 50f)
            return new Vector3(1f, 0.65f, 0f);
        return new Vector3(1f, 0f, 0f);
    }

    private static bool Contains(Box2 area, Vector2 point) =>
        point.X >= area.Left && point.X <= area.Right &&
        point.Y >= area.Bottom && point.Y <= area.Top;
}
