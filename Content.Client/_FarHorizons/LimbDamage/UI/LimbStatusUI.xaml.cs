using System.Numerics;
using Content.Shared._FarHorizons.LimbDamage.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._FarHorizons.LimbDamage.UI;

[GenerateTypedNameReferences]
public sealed partial class LimbStatusUI : UIWidget
{
    public bool HasTargetDisplay => LimbTargettingDisplay.DrawLimbs.Count > 0;

    public LimbStatusUI()
    {
        RobustXamlLoader.Load(this);
        UpdateTheme();
    }

    public void InitTarget(IPrototypeManager prototypes, SpriteSystem sprites, ProtoId<LimbTargettingPrototype> proto)
    {
        UpdateTheme();
        LimbTargettingDisplay.InitializeDisplay(prototypes, sprites, proto, withHealth: true);
        LimbTargettingDisplay.DefaultColor = Vector3.One;
        LimbTargettingDisplay.HighlightColor = Vector3.One;
        // Health display only
        LimbTargettingDisplay.HighlightSelection = false;
    }

    public void SetHealth(Dictionary<LimbTarget, float> damage)
    {
        LimbTargettingDisplay.LimbDamage = damage;
    }

    public void ShutdownTarget()
    {
        LimbTargettingDisplay.DrawLimbs.Clear();
        LimbTargettingDisplay.DrawLabels.Clear();
        LimbTargettingDisplay.LimbDamage.Clear();
        LimbTargettingDisplay.WithHealth = false;
        LimbTargettingDisplay.HighlightSelection = true;
        LimbTargettingDisplay.ClearShaders();
    }

    private void UpdateTheme()
    {
        if (BackgroundPanel.PanelOverride is StyleBoxTexture styleBox &&
            Theme.TryResolveTexture("template_small", out var texture))
            styleBox.Texture = texture;

        if (Theme.ResolveColor("slotText") is { } color)
            LimbTargettingDisplay.DefaultColor = new(color.R, color.G, color.B);
    }

    protected override void OnThemeUpdated()
    {
        base.OnThemeUpdated();
        UpdateTheme();
    }
}
